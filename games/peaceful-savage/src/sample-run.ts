function decoded(entry: string): RunRecord["inputs"][number] {
  const parts = /^(\d+)([acelmprv])(-?\d+)?$/u.exec(entry);
  const letter = parts?.[2] ?? "";
  if (parts === null || !isLetter(letter))
    throw new Error(`Not a sample input: ${entry}`);
  const tick = Number(parts[1]);
  const field = fieldOf(letter);
  return {
    data:
      field === null ? { tick } : { [field]: Number(parts[3] ?? "0"), tick },
    type: kinds[letter],
  };
}

